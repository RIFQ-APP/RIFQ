export function sectionNameAr(english: string): string {
  if (!english) return "";
  if (SECTION_AR[english]) return SECTION_AR[english];
  // partial match
  for (const [en, ar] of Object.entries(SECTION_AR)) {
    if (english.toLowerCase().includes(en.toLowerCase()) || en.toLowerCase().includes(english.toLowerCase())) {
      return ar;
    }
  }
  return english; // fallback
}
